def generate_questions_for_subject(subject_name: str, chapters_data: dict, target_count: int) -> List[Dict]:
    """为某个科目生成题目"""
    questions = []
    questions_per_chapter = target_count // len(chapters_data)
    question_index = 0  # 全局题目索引，确保唯一性
    
    for chapter_name, chapter_info in chapters_data.items():
        sections = chapter_info.get("sections", [])
        existing_questions = chapter_info.get("questions", [])
        
        if existing_questions:
            # 如果有现成题目，使用它们，并添加唯一标识符
            for i, q_data in enumerate(existing_questions):
                chapter_num = chapter_name.split(" ")[0] if " " in chapter_name else chapter_name
                unique_id = f"{subject_name[:2]}{chapter_num}{i+1}"
                q = {
                    "id": get_next_id(),
                    "chapter": chapter_name,
                    "section": sections[i % len(sections)] if sections else "综合练习",
                    "type": q_data.get("type", "single"),
                    "difficulty": random.randint(1, 5),
                    "question": f"({unique_id}){q_data['q']}",  # 添加唯一标识符
                    "options": q_data["opts"],
                    "answer": q_data["ans"],
                    "explanation": q_data["exp"],
                    "key_point": q_data["kp"],
                    "year": random.randint(2018, 2024)
                }
                questions.append(q)
                question_index += 1
        
        # 补充题目以达到目标数量
        chapter_question_count = len([q for q in questions if q["chapter"] == chapter_name])
        needed = max(0, questions_per_chapter - chapter_question_count)
        
        for i in range(needed):
            q = generate_unique_question(subject_name, chapter_name, sections, question_index)
            q["id"] = get_next_id()
            questions.append(q)
            question_index += 1
    
    # 确保达到目标数量
    while len(questions) < target_count:
        chapter_name = random.choice(list(chapters_data.keys()))
        sections = chapters_data[chapter_name].get("sections", [])
        q = generate_unique_question(subject_name, chapter_name, sections, question_index)
        q["id"] = get_next_id()
        questions.append(q)
        question_index += 1
    
    return questions[:target_count]


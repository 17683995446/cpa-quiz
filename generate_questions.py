def generate_unique_question(subject: str, chapter: str, sections: List[str], index: int) -> Dict:
    """生成唯一题目 - 确保每道题目都是唯一的"""
    templates = QUESTION_TEMPLATES.get(subject, QUESTION_TEMPLATES["会计"])
    
    # 根据章节生成相关题目
    chapter_num = chapter.split(" ")[0] if " " in chapter else chapter
    
    # 使用索引确保唯一性 - 每道题都有唯一的组合
    concept = templates["concepts"][index % len(templates["concepts"])]
    action = templates["actions"][index % len(templates["actions"])]
    condition = templates["conditions"][index % len(templates["conditions"])]
    
    # 使用更多变量组合确保唯一性

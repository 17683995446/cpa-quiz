def save_questions_to_files(questions_dict, output_dir):
    """将题目保存到JSON文件"""
    os.makedirs(output_dir, exist_ok=True)
    
    for subject, questions in questions_dict.items():
        filename = os.path.join(output_dir, f"{subject}.json")
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(questions, f, ensure_ascii=False, indent=2)
        print(f"已保存: {filename}")

def validate_questions(questions_dict):
    """验证题目质量"""
    print("\n========== 题目验证 ==========")
    
    total_questions = 0
    total_unique = 0
    
    for subject, questions in questions_dict.items():
        total = len(questions)
        unique_questions = len(set(q["question"] for q in questions))
        unique_ids = len(set(q["id"] for q in questions))
        
        total_questions += total
        total_unique += unique_questions
        
        print(f"\n{subject}:")
        print(f"  总题数: {total}")
        print(f"  唯一题目数: {unique_questions}")
        print(f"  唯一ID数: {unique_ids}")
        print(f"  唯一率: {unique_questions/total*100:.2f}%")
        
        # 检查章节分布
        chapters = {}
        for q in questions:
            chapter = q["chapter"]
            chapters[chapter] = chapters.get(chapter, 0) + 1
        
        print(f"  章节数: {len(chapters)}")
        print(f"  每章平均题数: {total/len(chapters):.1f}")
    
    print(f"\n总计:")
    print(f"  总题数: {total_questions}")
    print(f"  唯一题目数: {total_unique}")
    print(f"  总体唯一率: {total_unique/total_questions*100:.2f}%")
    
    return total_unique == total_questions

